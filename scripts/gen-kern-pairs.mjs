// Optical pair kerning for Zatiaras Display ExtraBold -> src/lib/kern-pairs.ts
//
// Every glyph has equal 0.05em side bearings and the font ships only ~30 kern pairs, so
// diagonal/flat pairs (A-T, L-T, P-A) read as big holes. For each pair this measures the
// ink gap row by row, averages it (deep concavities clamped), and pulls the pair toward the
// gap of H-H. The pull is limited so rows never get closer than 0.035em at -0.06em tracking.
//
// fontkit is not a project dependency. Run from a scratch dir that has it installed:
//   npm i fontkit && node gen-kern-pairs.mjs <font.woff2> <out.ts>
import * as fontkit from 'fontkit';
import fs from 'node:fs';

const [fontPath, outPath] = process.argv.slice(2);
const f = fontkit.openSync(fontPath);
const U = f.unitsPerEm;
const CAP = 0.7; // em
const ROWS = 36;
const CLAMP = 0.4; // em; ignore deeper concavities
const PULL = 0.55;
const MIN_CLEAR = 0.095; // em; min row gap before tracking (-0.06em) leaves 0.035em
const STEP = 0.005;
const KEEP = 0.02; // em; smaller adjustments are not worth shipping
const LETTERS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz';

function flatten(glyph) {
	const segs = [];
	let cur = null;
	let start = null;
	for (const { command, args: a } of glyph.path.commands) {
		if (command === 'moveTo') {
			cur = [a[0], a[1]];
			start = cur;
		} else if (command === 'lineTo') {
			segs.push([cur, [a[0], a[1]]]);
			cur = [a[0], a[1]];
		} else if (command === 'quadraticCurveTo') {
			let p = cur;
			for (let i = 1; i <= 10; i++) {
				const t = i / 10;
				const u = 1 - t;
				const q = [
					u * u * cur[0] + 2 * u * t * a[0] + t * t * a[2],
					u * u * cur[1] + 2 * u * t * a[1] + t * t * a[3]
				];
				segs.push([p, q]);
				p = q;
			}
			cur = [a[2], a[3]];
		} else if (command === 'bezierCurveTo') {
			let p = cur;
			for (let i = 1; i <= 12; i++) {
				const t = i / 12;
				const u = 1 - t;
				const q = [
					u ** 3 * cur[0] + 3 * u * u * t * a[0] + 3 * u * t * t * a[2] + t ** 3 * a[4],
					u ** 3 * cur[1] + 3 * u * u * t * a[1] + 3 * u * t * t * a[3] + t ** 3 * a[5]
				];
				segs.push([p, q]);
				p = q;
			}
			cur = [a[4], a[5]];
		} else if (command === 'closePath') {
			if (cur && start) segs.push([cur, start]);
			cur = start;
		}
	}
	return segs;
}

const cache = new Map();
function profile(ch) {
	if (cache.has(ch)) return cache.get(ch);
	const g = f.glyphForCodePoint(ch.codePointAt(0));
	const segs = flatten(g);
	const L = [];
	const R = [];
	for (let k = 0; k < ROWS; k++) {
		const y = ((k + 0.5) / ROWS) * CAP * U;
		let mn = Infinity;
		let mx = -Infinity;
		for (const [p, q] of segs) {
			if ((p[1] - y) * (q[1] - y) > 0 || p[1] === q[1]) continue;
			const x = p[0] + ((y - p[1]) / (q[1] - p[1])) * (q[0] - p[0]);
			mn = Math.min(mn, x);
			mx = Math.max(mx, x);
		}
		L.push(mn === Infinity ? null : mn / U);
		R.push(mx === -Infinity ? null : (g.advanceWidth - mx) / U);
	}
	const p = { L, R };
	cache.set(ch, p);
	return p;
}

function gaps(a, b) {
	const A = profile(a);
	const B = profile(b);
	const rows = [];
	for (let k = 0; k < ROWS; k++) if (A.R[k] != null && B.L[k] != null) rows.push(A.R[k] + B.L[k]);
	return rows;
}
const optical = (a, b) => {
	const r = gaps(a, b);
	return r.reduce((s, v) => s + Math.min(v, CLAMP), 0) / r.length;
};

const ref = optical('H', 'H');
const table = {};
for (const a of LETTERS) {
	for (const b of LETTERS) {
		let adj = -PULL * (optical(a, b) - ref);
		adj = Math.max(adj, MIN_CLEAR - Math.min(...gaps(a, b)));
		adj = Math.min(adj, 0.01);
		adj = Math.round(adj / STEP) * STEP;
		if (Math.abs(adj) >= KEEP) (table[a] ??= {})[b] = +adj.toFixed(3);
	}
}

const body = Object.entries(table)
	.map(
		([a, row]) =>
			`\t${a}: { ${Object.entries(row)
				.map(([b, v]) => `${b}: ${v}`)
				.join(', ')} }`
	)
	.join(',\n');
fs.writeFileSync(
	outPath,
	`// Generated by scripts/gen-kern-pairs.mjs; do not edit by hand.
// Optical pair kerning (em) for Zatiaras Display ExtraBold, keyed [left][right].
export const KERN_PAIRS: Record<string, Record<string, number>> = {
${body}
};
`
);
